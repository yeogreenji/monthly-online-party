import os
from playwright.sync_api import sync_playwright, expect
os.makedirs("artifacts",exist_ok=True)
with sync_playwright() as p:
    b=p.chromium.launch(args=["--use-gl=angle","--use-angle=swiftshader","--enable-unsafe-swiftshader"])
    for width,height in [(1280,900),(390,844)]:
        page=b.new_page(viewport={"width":width,"height":height},reduced_motion="reduce")
        errors=[]
        page.on("pageerror",lambda e:errors.append(str(e)))
        page.goto("http://127.0.0.1:4173")
        page.get_by_role("button",name="수달",exact=True).click()
        page.locator("#nickname").fill("딩동테스트")
        page.get_by_role("button",name="딩동 입장하기",exact=True).click()
        canvas=page.locator(".dd3-canvas canvas")
        expect(canvas).to_have_attribute("data-avatar-mode","2d-billboard",timeout=15000)
        page.locator(".dd-wardrobe summary").click()
        page.get_by_label("옷 색상",exact=True).select_option("#a45e68")
        expect(canvas).to_have_attribute("data-avatar-look",__import__("re").compile("#a45e68"))
        page.reload()
        expect(canvas).to_have_attribute("data-avatar-look",__import__("re").compile("#a45e68"),timeout=15000)
        page.locator("#dd3-dest").select_option("jazz")
        page.get_by_role("button",name="걸어가기",exact=True).click()
        expect(page.get_by_role("status").filter(has_text="연령·안전 확인 전 잠금")).to_be_visible()
        expect(canvas).to_have_attribute("data-room","hall")
        page.get_by_role("button",name="황동 초인종",exact=True).click()
        expect(canvas).to_have_attribute("data-last-prop","hub-bell",timeout=15000)
        expect(page.get_by_role("status").filter(has_text="새로운 방문객")).to_be_visible()
        for id in ["season","plaza"]:
            page.locator("#dd3-dest").select_option(id)
            page.get_by_role("button",name="걸어가기",exact=True).click()
            expect(canvas).to_have_attribute("data-room",id,timeout=35000)
            if id=="season":
                page.get_by_role("button",name="파티 테이블",exact=True).click()
                expect(canvas).to_have_attribute("data-last-prop","season-banquet",timeout=15000)
            page.get_by_role("button",name="채팅 접기",exact=True).click()
            page.get_by_role("button",name="채팅 펼치기",exact=True).click()
            expect(page.get_by_role("textbox",name="메시지",exact=True)).to_be_visible(timeout=5000)
            if id=="season":
                page.get_by_role("button",name="겨울 포토존",exact=True).click()
                expect(canvas).to_have_attribute("data-last-prop","season-photo",timeout=15000)
                page.get_by_role("button",name="포토존 사진 촬영",exact=True).click()
                expect(page.get_by_alt_text("첨부 미리보기")).to_be_visible()
                page.get_by_role("button",name="전송",exact=True).click()
                expect(page.get_by_alt_text("내가 올린 사진")).to_be_visible()
                page.get_by_role("button",name="장소 추천 첨부",exact=True).click()
                page.get_by_label("장소 이름",exact=True).fill("시연 장소")
                page.get_by_label("장소 링크",exact=True).fill("https://example.com/")
                page.get_by_role("button",name="전송",exact=True).click()
                page.get_by_role("button",name="장소 저장",exact=True).click()
                expect(page.get_by_text("저장한 장소 (1)",exact=True)).to_be_visible()
            page.get_by_role("button",name="파티 의자에 앉기" if id=="season" else "광장 벤치에 앉기",exact=True).click()
            expect(canvas).to_have_attribute("data-pose","seated",timeout=15000)
            page.screenshot(path=f"artifacts/seated-{id}-{width}.png")
            page.get_by_role("button",name="의자에서 일어나기",exact=True).click()
            expect(canvas).to_have_attribute("data-pose","standing")
            page.screenshot(path=f"artifacts/{id}-{width}.png")
            page.get_by_role("button",name="복도로 걷기",exact=True).click()
            expect(canvas).to_have_attribute("data-room","hall",timeout=20000)
        page.get_by_role("button",name="광장으로 돌아가기",exact=True).click()
        expect(page.get_by_role("status").filter(has_text="중앙 축제광장 · 도착")).to_be_visible(timeout=20000)
        expect(canvas).to_have_attribute("data-position","0.00,0.00")
        page.get_by_role("button",name="시즌 장식 숨기기",exact=True).click()
        expect(page.get_by_role("button",name="시즌 장식 보이기",exact=True)).to_be_visible()
        page.get_by_role("button",name="시즌 장식 보이기",exact=True).click()
        page.get_by_role("button",name="가벼운 2D 모드",exact=True).click()
        expect(page.locator(".dd3-fallback")).to_be_visible()
        page.locator("#dd3-dest").select_option("season")
        page.get_by_role("button",name="걸어가기",exact=True).click()
        expect(page.get_by_role("textbox",name="메시지",exact=True)).to_be_visible(timeout=5000)
        assert not errors,errors
        print(f"PASS {width}x{height}: wardrobe persistence, 3D rooms, lock, chat collapse, fallback")
        page.close()
    b.close()
