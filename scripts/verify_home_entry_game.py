from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    b=p.chromium.launch(args=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
    page=b.new_page(viewport={'width':390,'height':844},has_touch=True,is_mobile=True,reduced_motion='reduce')
    page.goto('http://127.0.0.1:4173')
    expect(page.locator('#dd-entry-avatar')).to_have_value('cat')
    cards=page.get_by_role('group',name='동물 캐릭터 고르기')
    expect(cards.get_by_role('button',name='고양이',exact=True)).to_have_attribute('aria-pressed','true')
    cards.get_by_role('button',name='곰돌이',exact=True).tap()
    expect(page.locator('#dd-entry-avatar')).to_have_value('bear')
    page.locator('#nickname').fill('검수 테스트')
    page.get_by_role('button',name='딩동 입장하기',exact=True).tap()
    canvas=page.locator('.dd3-canvas canvas')
    expect(canvas).to_have_attribute('data-avatar-key','bear',timeout=30000)
    def visit(room):
        if not page.locator('#dd3-dest').is_visible():page.get_by_role('button',name='설정',exact=True).tap()
        page.locator('#dd3-dest').select_option(room)
        page.get_by_role('button',name='바로 입장',exact=True).tap()
        expect(canvas).to_have_attribute('data-room',room,timeout=30000)
    visit('home')
    page.get_by_role('button',name='집 꾸미기 열기',exact=True).tap()
    page.get_by_role('button',name='꾸미기 화면 크게').tap()
    assert page.locator('.dd-home-expanded').bounding_box()['height']>720
    page.get_by_role('button',name='가구·배치').tap()
    page.get_by_role('button',name='배치 가구 책장 4').tap()
    page.get_by_role('button',name='선택한 가구 교체하기').tap()
    page.get_by_role('button',name='낮잠 침대',exact=True).tap()
    expect(page.get_by_role('button',name='배치 가구 낮잠 침대 4')).to_have_attribute('aria-pressed','true',timeout=20000)
    page.wait_for_function("JSON.parse(document.querySelector('.dd3-canvas canvas').dataset.homeConfig).items.some(i=>i.id==='home-shelf'&&i.kind==='🛏️')")
    page.get_by_role('button',name='집 꾸미기 저장',exact=True).tap()
    expect(page.get_by_text('집 꾸미기를 저장했어요.',exact=True)).to_be_visible()
    page.reload()
    visit('home')
    page.wait_for_function("JSON.parse(document.querySelector('.dd3-canvas canvas').dataset.homeConfig).items.some(i=>i.id==='home-shelf'&&i.kind==='🛏️')")
    print('PASS mobile 3D onboarding, full-size home, furniture replacement, durable save',flush=True)
    visit('games')
    page.locator('.dd-room-join').first.tap()
    page.get_by_role('button',name='미니게임 열기',exact=True).tap()
    page.get_by_role('button',name='스무고개',exact=True).tap()
    game=page.get_by_role('region',name='스무고개 게임')
    for query,reply in [('사람입니까?','아니오.'),('그럼 물건입니까?','네.'),('그러면 비 올 때 쓰나요?','네.')]:
        game.get_by_role('textbox').fill(query)
        game.get_by_role('button',name='입력 보내기').tap()
        expect(game.get_by_role('status')).to_contain_text('픽셀: '+reply)
    expect(game.get_by_role('list',name='질문 기록').get_by_role('listitem')).to_have_count(3)
    game.get_by_role('textbox').fill('우산')
    game.get_by_role('button',name='입력 보내기').tap()
    expect(game.get_by_role('status')).to_contain_text('4/20회 사용 · 정답이에요!')
    print('PASS mobile 3D three linked questions and answer')
    b.close()
