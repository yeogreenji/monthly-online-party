import re
from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    b=p.chromium.launch(args=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
    page=b.new_page(viewport={'width':390,'height':844},is_mobile=True,has_touch=True,reduced_motion='reduce')
    page.goto('http://127.0.0.1:4173')
    page.locator('#nickname').fill('모바일 테스트')
    page.get_by_role('button',name='딩동 입장하기',exact=True).tap()
    canvas=page.locator('.dd3-canvas canvas')
    expect(canvas).to_have_attribute('data-avatar-mode','3d-model',timeout=30000)
    page.get_by_role('button',name='화면 축소',exact=True).tap()
    page.get_by_role('button',name='화면 축소',exact=True).tap()
    page.wait_for_function("(()=>{const p=JSON.parse(document.querySelector('.dd3-canvas canvas').dataset.bellPoint||'[]');return p[0]>.1&&p[0]<.95})()")
    expect(canvas).to_have_attribute('data-bell-point',re.compile(r'^\['),timeout=15000)
    pt=canvas.evaluate('(c)=>JSON.parse(c.dataset.bellPoint)')
    rect=canvas.bounding_box()
    page.touchscreen.tap(rect['x']+pt[0]*rect['width'],rect['y']+pt[1]*rect['height'])
    expect(canvas).to_have_attribute('data-clicked-prop','hub-bell',timeout=10000)
    expect(canvas).to_have_attribute('data-last-prop','hub-bell')
    expect(page.locator('.dd-bell-burst span')).to_be_visible()
    print('PASS 3D bell direct tap')
    settings=page.get_by_role('button',name='설정',exact=True)
    dest=page.locator('#dd3-dest')
    for room in ('cafe','hobby','travel','cinema','women','men','games','season','home','plaza','jazz','single'):
        if not dest.is_visible(): settings.tap()
        dest.select_option(room)
        locked=room in ('jazz','single')
        page.get_by_role('button',name='공간 구경' if locked else '바로 입장',exact=True).tap()
        expect(canvas).to_have_attribute('data-room',room,timeout=20000)
        expect(canvas).to_have_attribute('data-room-mode','preview' if locked else 'open')
        if locked: expect(page.locator('.dd-messenger')).to_have_count(0)
        if room=='home':
            expect(canvas).to_have_attribute('data-sofa-point',re.compile(r'^\['),timeout=15000)
            pt=canvas.evaluate('(c)=>JSON.parse(c.dataset.sofaPoint)')
            rect=canvas.bounding_box()
            page.touchscreen.tap(rect['x']+pt[0]*rect['width'],rect['y']+pt[1]*rect['height'])
            expect(canvas).to_have_attribute('data-clicked-prop','home-sofa',timeout=15000)
            page.get_by_role('button',name='옷장',exact=True).tap()
            wardrobe=page.get_by_role('dialog',name='나의 옷장')
            wardrobe.get_by_role('button',name='의상',exact=True).tap()
            wardrobe.get_by_role('button',name='옷 색상',exact=True).tap()
            for name,hexcode in [('네온 핑크','#ff236f'),('코발트','#0059f8'),('스노우','#fffdfa')]:
                wardrobe.get_by_role('button',name=f'옷 색상 {name} 착용',exact=True).tap()
                expect(canvas).to_have_attribute('data-avatar-look',re.compile(hexcode),timeout=20000)
            wardrobe.get_by_role('button',name='착용 완료 · 옷장 닫기').tap()
            assert page.evaluate("JSON.parse(localStorage.getItem('dd.avatar.look.v1')).coat")== '#fffdfa'
        if not dest.is_visible(): settings.tap()
        page.get_by_role('button',name='복도로 걷기',exact=True).tap()
        expect(canvas).to_have_attribute('data-room','hall',timeout=30000)
        print('PASS room',room,flush=True)
    b.close()
