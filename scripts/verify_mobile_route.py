from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    b=p.chromium.launch(args=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
    page=b.new_page(viewport={'width':390,'height':844},has_touch=True,is_mobile=True,reduced_motion='reduce')
    page.goto('http://127.0.0.1:4173')
    page.locator('#nickname').fill('동선 테스트')
    page.get_by_role('button',name='딩동 입장하기',exact=True).tap()
    canvas=page.locator('.dd3-canvas canvas')
    expect(canvas).to_be_visible(timeout=20000)
    page.get_by_role('button',name='설정',exact=True).tap()
    page.locator('#dd3-dest').select_option('cafe')
    page.get_by_role('button',name='☆',exact=True).tap()
    page.get_by_role('button',name='지도',exact=True).tap()
    panel=page.get_by_role('dialog',name='마을 지도')
    panel.get_by_role('button',name='즐겨찾기 목적지',exact=True).tap()
    expect(panel.locator('.dd-map-grid button')).to_have_count(1)
    panel.get_by_role('button',name='전체 목적지',exact=True).tap()
    expect(panel.locator('.dd-map-grid button')).to_have_count(12)
    panel.locator('.dd-map-grid button').filter(has_text='낮과 밤의 카페').tap()
    expect(canvas).to_have_attribute('data-room','cafe')
    page.locator('.dd-room-join').first.tap()
    message=page.get_by_role('textbox',name='메시지',exact=True)
    message.fill('카페 초안')
    page.get_by_role('button',name='채팅 전체 화면',exact=True).tap()
    page.get_by_role('button',name='채팅에서 광장으로 돌아가기',exact=True).tap()
    expect(page.get_by_text('중앙 축제광장 · 도착',exact=True)).to_be_visible(timeout=60000)
    expect(canvas).to_have_attribute('data-position','0.00,0.00')
    page.get_by_role('button',name='지도',exact=True).tap()
    panel.locator('.dd-map-grid button').filter(has_text='낮과 밤의 카페').tap()
    page.locator('.dd-room-join').first.tap()
    expect(message).to_have_value('카페 초안')
    expect(page.get_by_role('button',name='채팅 전체 화면',exact=True)).to_be_visible()
    page.get_by_role('button',name='설정',exact=True).tap()
    expect(page.locator('#dd3-dest')).to_be_visible()
    page.locator('#dd3-dest').select_option('jazz')
    page.get_by_role('button',name='공간 구경',exact=True).tap()
    expect(canvas).to_have_attribute('data-room-mode','preview')
    expect(message).to_have_count(0)
    print('PASS: mobile 3D favorite filter, entry, full chat exit, hub, draft restore, settings and adult lock')
